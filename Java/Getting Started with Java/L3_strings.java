public class L3_strings {
    public static void main(String[] args) {
        String var1 = "Evan";
        String var2 = " Mendonsa";
        System.out.println(var1+var2);
        //Adding numbers if they were a String:-
        String num1 = "7";
        int num2 = 9;
        System.out.println(Integer.parseInt(num1)+num2);
    }
}

