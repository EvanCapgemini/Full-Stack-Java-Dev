public class L13_do_while_loops {
    public static void main(String[] args) {
        int i = 1;
        do {
            System.out.println(i);
            i++;
        } while(i<=5);
    }
}

/*
Notes:-

Do While Loop:-
syntax:
initialize/declaration;
do {
...;
increment/decrement; //Executes at-least once and then depends on the condition given.
}
while(condition);
*/