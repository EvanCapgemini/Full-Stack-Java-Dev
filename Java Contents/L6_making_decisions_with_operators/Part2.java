package L6_making_decisions_with_operators;

public class Part2 {
    public static void main(String[] args) {
        int num1=5;
        if(num1>=5){
            System.out.println(num1+" is greater than or equal to 5.");
        }
        else{
            System.out.println(num1+" is less than 5.");
        }
    }
}

/*
Notes:-

More comparison operators:
> --> greater than
< --> less than
>= --> greater than or equal to
<= --> less than or equal to
*/