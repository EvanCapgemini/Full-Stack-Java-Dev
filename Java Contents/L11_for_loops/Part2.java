package L11_for_loops;

public class Part2 {
    public static void main(String[] args) {
        //Without passing values/conditions in parentheses.
        int i = 1;
        for(;;){
            if(i<=10) {
                System.out.println(i);
                i++;
            }
        }
    }
}

