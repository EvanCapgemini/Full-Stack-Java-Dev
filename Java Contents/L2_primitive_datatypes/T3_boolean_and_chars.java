package L2_primitive_datatypes;

public class T3_boolean_and_chars {
    public static void main(String[] args) {
        boolean var1 = false;
        System.out.println(var1);
        char alpha1 = 'a';
        System.out.println(alpha1);
        //How to display a character using unicode value:
        char alpha2 = '\u00A7';
        System.out.println(alpha2);
    }
}

/*
Notes:-

Boolean:
* Accepts only 2 values --> true/false

Char:
* Only accepts characters of length 1 --> Each character has a unique unicode value.
*/
