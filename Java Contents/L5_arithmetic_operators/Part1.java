package L5_arithmetic_operators;

public class Part1 {
    public static void main(String[] args) {
        int a = 10;
        int b = 11;
        int sum = a + b;
        System.out.println(sum);
        String name = "Evan";
        System.out.println(name + " M");
    }
}

/*
Notes:-

= --> Assignment
+ --> Addition / Concatenation
- --> Subtraction
* --> Multiplication
/ --> Division
Priority : brackets > order > multiplication/division > addition/subtraction.
*/