public class L12_while_loops {
    public static void main(String[] args) {
        int i = 1;
        while(i<=5){
            System.out.println("Iteration "+i+".");
            i++;
        }
    }
}

/*
Notes:-

While Loop:-
syntax:
initialization/declaration;
while(condition){
...;
increment/decrement; //Executes as long as condition is true.
}
*/